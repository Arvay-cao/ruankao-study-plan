<h2>9. 安全防护措施</h2>
<ul>
<li><b>防火墙</b>：内网与外网间的访问控制屏障。<b>包过滤</b>（工作在<b>网络层</b>，按 IP/端口规则丢包）、应用网关/代理（应用层，彻底但慢）、状态检测（兼顾）。局限：防外不防内，对绕过端口的应用层攻击乏力。</li>
