<h3>3.3 多重度（每年必考 1—2 空）</h3>
<table>
<tr><th>写法</th><th>含义</th></tr>
<tr><td>1</td><td>恰好一个</td></tr>
<tr><td>0..1</td><td>零个或一个（可以有，最多一个）</td></tr>
