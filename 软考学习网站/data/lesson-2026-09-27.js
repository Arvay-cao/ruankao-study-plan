<h2>1. 面向对象分析的核心动作：找类、定关系、分职责</h2>
<p>面向对象分析（OOA）把系统看成一组<b>协同工作的对象</b>。试题三的三个固定动作：</p>
<ol>
<li><b>找类</b>：名词分析法——题干中的业务名词（订单、停车记录、电梯）→ 类候选；属性（下单时间、费用）挂到对应类上。</li>
<li><b>定关系</b>：类之间的结构关系（泛化/实现/组合/聚合/关联/依赖）+ 数量关系（多重度）。</li>
<li><b>分职责</b>：每个操作（方法）应该放在哪个类上——考试问"××操作应由哪个类负责"。</li>
</ol>

