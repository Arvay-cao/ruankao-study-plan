<div class="callout warn">
<div class="callout-title">双端标注法（防错关键）</div>
<p>类A—类B关联：站在A看"一个A连几个B"，结果标在<b>B端</b>；站在B看"一个B连几个A"，结果标在<b>A端</b>。<b>两端的多重度分别独立判断，不要互推。</b>例：订单(1)—(1..*)订单明细、商品(1)—(0..*)订单明细——明细端对订单是1（一条明细只属一单），对商品也是1（一条明细只对应一种商品），但商品端看明细是 0..*（一种商品可以被多次购买）。</p>
</div>

