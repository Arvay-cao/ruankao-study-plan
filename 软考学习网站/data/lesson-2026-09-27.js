<p>相关原则（了解即可，用于选项辨析）：<b>单一职责</b>（一个类只做一类事）、<b>开闭原则</b>（对扩展开放、对修改关闭）、<b>依赖倒置</b>（依赖抽象不依赖具体）。考试中"信息专家"最常以"该操作应放哪个类"的形式出现。</p>

